#!/usr/bin/env python3
"""Regenerate research/INDEX.md and the per-topic README files from sources.json.

Usage: python3 research/scripts/build_index.py

sources.json is the single source of truth. This script only reads it and
rewrites generated Markdown, so it is safe to run as often as you like.
"""

import json
import os
import sys
from collections import Counter

RESEARCH_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCES_PATH = os.path.join(RESEARCH_DIR, "sources.json")
TOPICS_PATH = os.path.join(RESEARCH_DIR, "topics.json")
LIBRARY_DIR = os.path.join(RESEARCH_DIR, "library")

TYPE_LABELS = {
    "consensus-statement": "Consensus statement",
    "position-stand": "Position stand",
    "clinical-practice-guideline": "Clinical practice guideline",
    "public-health-guideline": "Public health guideline",
    "umbrella-review": "Umbrella review",
    "meta-analysis": "Meta-analysis",
    "systematic-review": "Systematic review",
    "rct": "Randomized controlled trial",
    "cohort": "Cohort study",
    "case-control": "Case-control study",
    "cross-sectional": "Cross-sectional study",
    "experimental": "Experimental study",
    "narrative-review": "Narrative review",
    "organization-guide": "Organization guide",
    "training-plan-template": "Training plan template",
    "coaching-manual": "Coaching manual",
    "book": "Book",
    "book-chapter": "Book chapter",
    "thesis": "Thesis",
    "preprint": "Preprint",
    "other": "Other",
}
TYPE_ORDER = {t: i for i, t in enumerate(TYPE_LABELS)}

ACCESS_LABELS = {
    "open-license": "Open licence",
    "free-to-read": "Free to read",
    "paywalled": "Paywalled",
    "unknown": "Unknown",
}


def load_json(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def topic_dir_name(topic):
    return "%02d-%s" % (topic["number"], topic["slug"])


def md_escape_cell(text):
    return (text or "").replace("|", "\\|").replace("\n", " ").strip()


def short_authors(authors):
    if not authors:
        return "Unknown"
    first = authors.split(",")[0].strip()
    if "," in authors or "et al" in authors:
        first = first.replace("et al.", "").replace("et al", "").strip()
        return first + " et al."
    return first


def links_for(src):
    links = []
    if src.get("doi"):
        links.append("[DOI](https://doi.org/%s)" % src["doi"])
    if src.get("pmid"):
        links.append("[PubMed](https://pubmed.ncbi.nlm.nih.gov/%s/)" % src["pmid"])
    if src.get("pmcid"):
        links.append("[PMC](https://pmc.ncbi.nlm.nih.gov/articles/%s/)" % src["pmcid"])
    if src.get("url") and not (src.get("doi") and src["url"].lower().endswith(src["doi"].lower())):
        links.append("[Web](%s)" % src["url"])
    if src.get("pdf_url"):
        links.append("[PDF link](%s)" % src["pdf_url"])
    return " · ".join(links)


def access_text(src):
    label = ACCESS_LABELS.get(src.get("access") or "unknown", src.get("access") or "Unknown")
    if src.get("license"):
        label += " (%s)" % src["license"]
    return label


def local_files(src):
    """Downloaded copies in the git-ignored library-local/, as paths relative to research/."""
    return [p for p in (src.get("local_files") or {}).values() if p]


def copy_text(src, with_paths=False):
    files = local_files(src)
    if not files:
        return "Citation only"
    label = "Local"
    if src.get("open_licence_copies"):
        label += " (openly licensed)"
    if with_paths:
        label += " " + ", ".join("`%s`" % p for p in sorted(files))
    return label


def sort_key(src):
    return (TYPE_ORDER.get(src.get("source_type"), 99), -(src.get("year") or 0), src["id"])


def build_topic_readme(topic, primary, secondary, topic_by_slug):
    folder = os.path.join(LIBRARY_DIR, topic_dir_name(topic))
    os.makedirs(folder, exist_ok=True)
    lines = []
    lines.append("# %02d. %s" % (topic["number"], topic["title"]))
    lines.append("")
    lines.append("**Question:** %s" % topic["question"])
    lines.append("")
    with_copy = sum(1 for s in primary if local_files(s))
    lines.append(
        "%d sources filed here (%d with a downloaded copy in the git-ignored `research/library-local/`), plus %d filed under other topics that are also relevant."
        % (len(primary), with_copy, len(secondary))
    )
    lines.append("")
    lines.append("This file is generated by `research/scripts/build_index.py` from `research/sources.json`; edit the JSON, not this file.")
    lines.append("")
    current_type = None
    for src in sorted(primary, key=sort_key):
        stype = src.get("source_type") or "other"
        if stype != current_type:
            current_type = stype
            lines.append("## %s" % TYPE_LABELS.get(stype, stype))
            lines.append("")
        lines.append('<a id="%s"></a>' % src["id"])
        lines.append("### %s" % (src.get("title") or src["id"]))
        lines.append("")
        cite = "%s (%s). *%s*." % (src.get("authors") or "Unknown", src.get("year") or "n.d.", src.get("venue") or "")
        lines.append(cite)
        lines.append("")
        meta = ["`%s`" % src["id"], TYPE_LABELS.get(stype, stype), access_text(src), "Copy: " + copy_text(src, with_paths=True)]
        lines.append(" · ".join(meta))
        link_line = links_for(src)
        if link_line:
            lines.append("")
            lines.append(link_line)
        lines.append("")
        if src.get("summary"):
            lines.append("**Summary (initial read):** %s" % src["summary"].strip())
            lines.append("")
        if src.get("relevance"):
            lines.append("**Why it is here:** %s" % src["relevance"].strip())
            lines.append("")
        other_topics = [t for t in (src.get("topics") or [])[1:] if t in topic_by_slug]
        if other_topics:
            lines.append("**Also tagged:** " + ", ".join(topic_by_slug[t]["title"] for t in other_topics))
            lines.append("")
        if src.get("abstract"):
            source_note = " (from %s)" % src["abstract_source"] if src.get("abstract_source") else ""
            lines.append("<details><summary>Abstract%s</summary>" % source_note)
            lines.append("")
            lines.append(src["abstract"].strip())
            lines.append("")
            lines.append("</details>")
            lines.append("")
    if secondary:
        lines.append("## Also relevant (filed under other topics)")
        lines.append("")
        for src in sorted(secondary, key=sort_key):
            home = topic_by_slug[src["topics"][0]]
            lines.append(
                "- [%s (%s): %s](../%s/README.md#%s)"
                % (short_authors(src.get("authors")), src.get("year") or "n.d.", src.get("title"), topic_dir_name(home), src["id"])
            )
        lines.append("")
    with open(os.path.join(folder, "README.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines).rstrip() + "\n")


def build_index(sources, topics, topic_by_slug):
    lines = []
    lines.append("# Source index")
    lines.append("")
    lines.append("Every source collected for the distance running literature review, grouped by primary topic.")
    lines.append("Generated by `research/scripts/build_index.py` from `research/sources.json`; edit the JSON, not this file.")
    lines.append("")
    access = Counter(s.get("access") or "unknown" for s in sources)
    types = Counter(s.get("source_type") or "other" for s in sources)
    with_copy = sum(1 for s in sources if local_files(s))
    open_copy = sum(1 for s in sources if local_files(s) and s.get("open_licence_copies"))
    lines.append(
        "**%d sources.** %d have a full-text copy downloaded by `scripts/fetch_library.py` into the git-ignored `library-local/` folder (%d of them openly licensed); the rest are citation, link and abstract only. Full texts are never committed."
        % (len(sources), with_copy, open_copy)
    )
    lines.append("")
    lines.append("By access: " + ", ".join("%s %d" % (ACCESS_LABELS.get(k, k), v) for k, v in access.most_common()) + ".")
    lines.append("")
    lines.append("By type: " + ", ".join("%s %d" % (TYPE_LABELS.get(k, k), v) for k, v in types.most_common()) + ".")
    lines.append("")
    lines.append("| # | Topic | Sources |")
    lines.append("|---|---|---|")
    by_topic = {t["slug"]: [] for t in topics}
    for s in sources:
        by_topic[s["topics"][0]].append(s)
    for t in topics:
        lines.append("| %02d | [%s](#%02d-%s) | %d |" % (t["number"], t["title"], t["number"], t["slug"], len(by_topic[t["slug"]])))
    lines.append("")
    for t in topics:
        lines.append('<a id="%02d-%s"></a>' % (t["number"], t["slug"]))
        lines.append("## %02d. %s" % (t["number"], t["title"]))
        lines.append("")
        lines.append("%s Details and summaries: [library/%s/README.md](library/%s/README.md)" % (t["question"], topic_dir_name(t), topic_dir_name(t)))
        lines.append("")
        rows = sorted(by_topic[t["slug"]], key=sort_key)
        if not rows:
            lines.append("_No sources yet._")
            lines.append("")
            continue
        lines.append("| Source | Year | Type | Access | Copy |")
        lines.append("|---|---|---|---|---|")
        for s in rows:
            title = md_escape_cell(s.get("title"))
            link = "library/%s/README.md#%s" % (topic_dir_name(t), s["id"])
            lines.append(
                "| %s. [%s](%s) | %s | %s | %s | %s |"
                % (
                    md_escape_cell(short_authors(s.get("authors"))).rstrip("."),
                    title,
                    link,
                    s.get("year") or "n.d.",
                    TYPE_LABELS.get(s.get("source_type"), s.get("source_type")),
                    md_escape_cell(access_text(s)),
                    copy_text(s),
                )
            )
        lines.append("")
    with open(os.path.join(RESEARCH_DIR, "INDEX.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines).rstrip() + "\n")


def main():
    sources = load_json(SOURCES_PATH)
    topics = load_json(TOPICS_PATH)
    topic_by_slug = {t["slug"]: t for t in topics}
    problems = []
    seen = set()
    for s in sources:
        if s["id"] in seen:
            problems.append("duplicate id %s" % s["id"])
        seen.add(s["id"])
        if not s.get("topics") or s["topics"][0] not in topic_by_slug:
            problems.append("%s has no valid primary topic" % s["id"])
    if problems:
        sys.exit("sources.json problems:\n  " + "\n  ".join(problems))
    for t in topics:
        primary = [s for s in sources if s["topics"][0] == t["slug"]]
        secondary = [s for s in sources if t["slug"] in s["topics"][1:]]
        build_topic_readme(t, primary, secondary, topic_by_slug)
    build_index(sources, topics, topic_by_slug)
    print("Wrote INDEX.md and %d topic READMEs for %d sources." % (len(topics), len(sources)))


if __name__ == "__main__":
    main()
